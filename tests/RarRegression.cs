using System.Buffers.Binary;
using System.Diagnostics;
using System.IO;
using System.Security.Cryptography;
using System.Text;
using MirrorFlux.Services;
using SharpCompress.Readers;

internal static class RarRegression
{
    internal static void Run(Action<bool, string> check)
    {
        string directory = Path.Combine(Path.GetTempPath(), "mf-rar-test-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(directory);
        try
        {
            byte[] payload = Encoding.UTF8.GetBytes("MirrorFlux generated RAR fixture\n");
            string archive = Path.Combine(directory, "sample.rar");
            using (var output = File.Create(archive))
            {
                Begin(output, 0);
                FileEntry(output, "empty", [], 0xe0, 0, 0);
                FileEntry(output, "hello.txt", payload, 0, payload.Length, Crc(payload));
                FileEntry(output, "hello.txt", [1,2,3], 0, 3, Crc([1,2,3]));
                End(output);
            }
            using (var rar = RarArchiveAdapter.Open(archive, new ReaderOptions()))
            {
                var entries = rar.Entries.ToArray();
                check(entries.Length == 3 && entries[0].IsDirectory && entries[0].Key == "empty", "RAR preserves empty directory entries");
                using var input = entries[1].OpenEntryStream(); using var memory = new MemoryStream(); input.CopyTo(memory);
                check(memory.ToArray().SequenceEqual(payload), "RAR stored entry decodes exact generated bytes");
                check(input.Read(new byte[1],1,0)==0, "RAR stream accepts a zero read at buffer end");
                using var duplicate = entries[2].OpenEntryStream(); using var other = new MemoryStream(); duplicate.CopyTo(other);
                check(other.ToArray().SequenceEqual(new byte[]{1,2,3}), "RAR duplicate names preserve entry identity");
                var held = entries[1].OpenEntryStream(); rar.Dispose();
                bool closed = false; try { held.ReadByte(); } catch (ObjectDisposedException) { closed = true; }
                check(closed, "Disposing RAR closes outstanding native entry handles");
            }
            string first = Path.Combine(directory,"split.part01.rar"), second=Path.Combine(directory,"split.part02.rar");
            using (var output=File.Create(first)) { Begin(output,0x101); FileEntry(output,"hello.txt",payload[..9],2,payload.Length,0); End(output); }
            using (var output=File.Create(second)) { Begin(output,1); FileEntry(output,"hello.txt",payload[9..],1,payload.Length,Crc(payload)); End(output); }
            using(var rar=RarArchiveAdapter.Open(first,new ReaderOptions()))
            {
                var entry=rar.Entries.Single();using var input=entry.OpenEntryStream();using var memory=new MemoryStream();input.CopyTo(memory);
                check(memory.ToArray().SequenceEqual(payload),"RAR split volume segments join without changing source archives");
            }
            byte[] corrupt=File.ReadAllBytes(second);corrupt[7+13+2]^=1;File.WriteAllBytes(second,corrupt);
            bool failed=false;try { using var rar=RarArchiveAdapter.Open(first,new ReaderOptions()); }catch(InvalidDataException){failed=true;}
            check(failed,"RAR split volume rejects damaged headers before extraction");
            string? sevenZip = Environment.GetEnvironmentVariable("MF_TEST_7ZIP");
            if (!string.IsNullOrEmpty(sevenZip))
            {
                byte[] text = Encoding.UTF8.GetBytes(string.Concat(Enumerable.Repeat("PPMd 共有処理の回帰検査\n", 2000)));
                string source = Path.Combine(directory, "日本語.txt"); File.WriteAllBytes(source, text);
                foreach (string format in new[] { "7z", "zip" })
                {
                    string compressed = Path.Combine(directory, "ppmd." + format);
                    var info = new ProcessStartInfo(sevenZip) { UseShellExecute = false, CreateNoWindow = true,
                        RedirectStandardOutput = true, RedirectStandardError = true };
                    foreach (string arg in new[] { "a", "-t" + format, format == "7z" ? "-m0=PPMd" : "-mm=PPMd", "--", compressed, source })
                        info.ArgumentList.Add(arg);
                    using var process = Process.Start(info)!;
                    var output = process.StandardOutput.ReadToEndAsync(); var error = process.StandardError.ReadToEndAsync();
                    process.WaitForExit();
                    if (process.ExitCode != 0) throw new Exception(output.Result + error.Result);
                    using var ppmd = RarArchiveAdapter.Open(compressed, new ReaderOptions());
                    using var stream = ppmd.Entries.Single(e => !e.IsDirectory).OpenEntryStream();
                    check(SHA256.HashData(stream).SequenceEqual(SHA256.HashData(text)),
                        "RAR removal preserves shared PPMd decoding for " + format);
                }
            }
            string[] types=typeof(SharpCompress.Archives.IArchive).Assembly.GetTypes().Select(t=>t.FullName??"").ToArray();
            check(!types.Any(t=>t.StartsWith("SharpCompress.Compressors.Rar.")||t.StartsWith("SharpCompress.Archives.Rar.")),"SharpCompress assembly contains no removed RAR implementation");
        }
        finally { Directory.Delete(directory,true); }
    }
    private static void Begin(Stream output,int flags){output.Write("Rar!\x1a\x07\x00"u8);byte[] h=new byte[13];h[2]=0x73;Set16(h,3,flags);Set16(h,5,h.Length);Fix(h);output.Write(h);}
    private static void End(Stream output){byte[] h=[0,0,0x7b,0,0,7,0];Fix(h);output.Write(h);}
    private static void FileEntry(Stream output,string name,byte[] data,int flags,int total,uint crc)
    {
        byte[] n=Encoding.ASCII.GetBytes(name),h=new byte[32+n.Length];h[2]=0x74;Set16(h,3,flags|0x8000);Set16(h,5,h.Length);
        Set32(h,7,(uint)data.Length);Set32(h,11,(uint)total);h[15]=2;Set32(h,16,crc);h[24]=20;h[25]=0x30;Set16(h,26,n.Length);Set32(h,28,(flags&0xe0)==0xe0?16u:32u);n.CopyTo(h,32);Fix(h);output.Write(h);output.Write(data);
    }
    private static void Set16(byte[] b,int o,int v)=>BinaryPrimitives.WriteUInt16LittleEndian(b.AsSpan(o),(ushort)v);
    private static void Set32(byte[] b,int o,uint v)=>BinaryPrimitives.WriteUInt32LittleEndian(b.AsSpan(o),v);
    private static void Fix(byte[] b)=>Set16(b,0,(int)(Crc(b.AsSpan(2))&0xffff));
    private static uint Crc(ReadOnlySpan<byte> data){uint c=uint.MaxValue;foreach(byte b in data){c^=b;for(int i=0;i<8;i++)c=(c>>1)^((c&1)!=0?0xedb88320u:0u);}return ~c;}

    internal static void Compare(string directory)
    {
        string seven=Environment.GetEnvironmentVariable("MF_TEST_7ZIP")??@"C:\Program Files\7-Zip\7z.exe";
        int pass=0,fail=0;
        foreach(string path in Directory.EnumerateFiles(directory,"*.rar").Order())
        {
            string name=Path.GetFileName(path);
            if(!name.StartsWith("Rar",StringComparison.OrdinalIgnoreCase)||name.Contains("encrypt",StringComparison.OrdinalIgnoreCase)||name.Contains("invalid",StringComparison.OrdinalIgnoreCase))continue;
            if(System.Text.RegularExpressions.Regex.IsMatch(name,@"\.part(?!0*1\.rar)\d+\.rar$",System.Text.RegularExpressions.RegexOptions.IgnoreCase))continue;
            bool reject = name is "Rar.malformed_512byte.rar" or "Rar5.comment.filesOnly.rar";
            try
            {
                using var archive=RarArchiveAdapter.Open(path,new ReaderOptions());
                foreach(var entry in archive.Entries.Where(e=>!e.IsDirectory))
                {
                    using var input=entry.OpenEntryStream();byte[] actual=SHA256.HashData(input);
                    var info=new ProcessStartInfo(seven){UseShellExecute=false,CreateNoWindow=true,RedirectStandardOutput=true,RedirectStandardError=true};
                    foreach(string arg in new[]{"x","-so","-spd","-y","--",path,entry.Key!})info.ArgumentList.Add(arg);
                    using var process=Process.Start(info)!;var error=process.StandardError.ReadToEndAsync();byte[] expected=SHA256.HashData(process.StandardOutput.BaseStream);process.WaitForExit();
                    if(process.ExitCode!=0||!actual.SequenceEqual(expected))throw new Exception("7-Zip mismatch: "+entry.Key+" "+error.GetAwaiter().GetResult());
                }
                if (reject) throw new Exception("Expected malformed/encrypted RAR rejection");
                Console.WriteLine("PASS RAR cross-check "+name);pass++;
            }
            catch(InvalidDataException ex) when (reject)
            { Console.WriteLine("PASS RAR rejection "+name+": "+ex.Message);pass++; }
            catch(Exception ex){Console.WriteLine("FAIL RAR cross-check "+name+": "+ex.Message);fail++;}
        }
        Console.WriteLine($"RAR cross-check: {pass} passed, {fail} failed");
        if(fail>0)throw new Exception("RAR compatibility comparison failed");
    }
}
